import { readFile, stat, writeFile } from "node:fs/promises";
import { basename, dirname, join } from "node:path";

const [tag, installer] = process.argv.slice(2);
const version = /^v?((?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*))$/.exec(tag)?.[1];
if (!version || !installer) {
  throw new Error("Usage: node apps/desktop/scripts/prepare-update.mjs vX.Y.Z <signed-installer.exe>");
}

const asset = `DeskBrawl_${version}_x64-setup.exe`;
if (basename(installer) !== asset) {
  throw new Error(`The installer for ${tag} must be named ${asset}`);
}
const info = await stat(installer);
if (!info.isFile() || info.size === 0) {
  throw new Error("The installer must be a non-empty file");
}

const signature = (await readFile(`${installer}.sig`, "utf8")).trim();
if (!/^[A-Za-z0-9+/]+={0,2}$/.test(signature) || signature.length % 4 !== 0) {
  throw new Error("Use the .sig file generated by the Tauri build for this installer");
}

const url = `https://github.com/Jinoko01/deskbrawl/releases/download/${tag}/DeskBrawl_x64-setup.exe`;
const manifest = { version, platforms: { "windows-x86_64": { signature, url } } };
const output = join(dirname(installer), "latest.json");
await writeFile(output, `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Wrote ${output}`);
